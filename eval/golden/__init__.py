"""Golden query sets: hand-labelled queries for measuring retrieval quality.

"Hand-labelled" means every judgment is grounded in a real, live-verified product -
not invented from memory, not generated by an LLM guessing at what "should" match.
Each query in `demo_fashion_in.py` etc. was built by finding a real anchor product (or
cluster) in the live catalog first, then writing a query a shopper could plausibly
type for it, then recording judgments from what an actual `hybrid()` call against the
live tenant returned (see `scripts/build_golden_sets.py` for the verification helpers
used while authoring these).

**Honest limitation, stated once here rather than per-file**: judgments are a
*verified top-K pool* - the top ~10-15 hits for the anchor query/cluster, individually
judged - not an exhaustive scan of which of a catalog's thousands of products are
relevant. That's standard practice for a constructed golden set, and it's sufficient
for what this project's eval actually needs: comparing configurations (alpha values,
rerank on/off, `retrieve_top_k`) against the *same* judged set. It is not a claim that
`recall@k` here is an absolute percentage of every relevant item in the whole catalog -
`eval/report.py` says so explicitly rather than let a percentage imply more than it
measures.

`relevance` is graded 0-2: 2 = the exact anchor(s) the query was built from, 1 =
genuinely on-topic-but-broader (same brand, more general garment; dressy but not
quite the anchor's category), 0 = not recorded at all - a hit that didn't clearly
belong was left out of `judgments` rather than force-labelled.
"""

from __future__ import annotations

import importlib
from dataclasses import dataclass, field

from app.retrieval.base import QueryClass


@dataclass(frozen=True)
class GoldenQuery:
    """One labelled query: what a shopper might type, and which SKUs answer it."""

    id: str
    query: str
    query_class: QueryClass
    judgments: dict[str, int] = field(default_factory=dict)
    note: str | None = None


# Explicit, not derived from the tenant string - a typo'd tenant name should fail
# loudly here rather than silently importing the wrong module or none at all.
_TENANT_MODULES = {
    "demo-fashion-in": "demo_fashion_in",
    "demo-electronics-in": "demo_electronics_in",
    "demo-home-goods": "demo_home_goods",
}


def load_golden_set(tenant: str) -> list[GoldenQuery]:
    """The labelled queries for one demo tenant."""
    module_name = _TENANT_MODULES.get(tenant)
    if module_name is None:
        raise ValueError(f"no golden set registered for tenant {tenant!r}")
    module = importlib.import_module(f"eval.golden.{module_name}")
    return list(module.QUERIES)
